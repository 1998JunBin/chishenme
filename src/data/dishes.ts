function difficultyOf(time: number): Difficulty {
  return time <= 15 ? 'easy' : time <= 45 ? 'medium' : 'hard'
}

function reasonFor(tags: string[], time: number): string {
  if (time >= 60) return '🕐 慢炖更香'
  if (tags.includes('辣')) return '🌶 符合你的口味'
  if (tags.includes('酸甜')) return '🍋 开胃'
  if (tags.includes('下饭')) return '🍚 下饭好菜'
  if (tags.includes('快手')) return '⚡ 适合快速晚餐'
  if (tags.includes('清淡')) return '🌿 健康之选'
  if (tags.includes('高蛋白')) return '💪 营养均衡'
  return '❤️ 你可能会喜欢'
}

/** 各分类在图库中的起始偏移，避免相邻菜共用一张图 */
const CATEGORY_OFFSET: Record<Category, number> = { meat: 0, veg: 21, soup: 43 }

function build(rows: Row[], category: Category, prefix: string): Dish[] {
  const offset = CATEGORY_OFFSET[category]
  return rows.map(([name, time, tags], i) => ({
    id: `${prefix}${String(i + 1).padStart(2, '0')}`,
    name,
    category,
    time,
    difficulty: difficultyOf(time),
    tags,
    reason: reasonFor(tags, time),
    image: img(IMAGE_IDS[(offset + i * 3) % IMAGE_IDS.length]),
  }))
}

